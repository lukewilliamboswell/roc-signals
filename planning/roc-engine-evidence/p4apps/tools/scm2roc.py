"""scm2roc.py SPEC_DIR MODULE OUT.roc [--skip NAME ...]

Convert an example's semantic `.scm` specs into Roc data for src/Spec.roc.
Metric assertions (mark-metrics, expect-metric-delta*) become `Mark`: they
name the current engine's counters, which the p4 engine does not have; the p4
harness measures work with exact allocation baselines instead.
"""
import sys, os, re

def tokenize(s):
    toks, i = [], 0
    while i < len(s):
        c = s[i]
        if c == ';':
            while i < len(s) and s[i] != '\n': i += 1
        elif c.isspace(): i += 1
        elif c in '()': toks.append(c); i += 1
        elif c == '"':
            j, out = i + 1, []
            while s[j] != '"':
                if s[j] == '\\': out.append(s[j + 1]); j += 2
                else: out.append(s[j]); j += 1
            toks.append(('str', ''.join(out))); i = j + 1
        else:
            j = i
            while j < len(s) and not s[j].isspace() and s[j] not in '()': j += 1
            toks.append(('sym', s[i:j])); i = j
    return toks

def parse(toks):
    stack = [[]]
    for t in toks:
        if t == '(': stack.append([])
        elif t == ')':
            x = stack.pop(); stack[-1].append(x)
        else: stack[-1].append(t)
    return stack[0]

def rs(s):
    return '"' + s.replace('\\', '\\\\').replace('"', '\\"').replace('$', '\\$') + '"'

def loc(x):
    head = x[0][1]
    if head == 'label': return f'Label({rs(x[1][1])})'
    if head == 'test-id': return f'TestId({rs(x[1][1])})'
    if head == 'text': return f'Text({rs(x[1][1])})'
    if head == 'role':
        assert x[2] == ('sym', ':name'), x
        return f'Role({rs(x[1][1])}, {rs(x[3][1])})'
    raise SystemExit(f'unknown locator {x}')

def boolean(t):
    return {'true': 'True', 'false': 'False'}[t[1]]

def step(x):
    h = x[0][1]
    if h == 'click': return f'Click({loc(x[1])})'
    if h == 'fill': return f'Fill({loc(x[1])}, {rs(x[2][1])})'
    if h == 'check': return f'Check({loc(x[1])}, True)'
    if h == 'uncheck': return f'Check({loc(x[1])}, False)'
    if h == 'select-option': return f'Choose({loc(x[1])}, {rs(x[2][1])})'
    if h == 'expect-text': return f'ExpText({loc(x[1])}, {rs(x[2][1])})'
    if h == 'expect-value': return f'ExpValue({loc(x[1])}, {rs(x[2][1])})'
    if h == 'expect-checked': return f'ExpChecked({loc(x[1])}, {boolean(x[2])})'
    if h == 'expect-disabled': return f'ExpDisabled({loc(x[1])}, {boolean(x[2])})'
    if h == 'expect-visible': return f'ExpVisible({loc(x[1])})'
    if h == 'expect-absent': return f'ExpAbsent({loc(x[1])})'
    if h == 'expect-attr':
        v = x[3][1]
        return f'ExpAttr({loc(x[1])}, {rs(x[2][1])}, {rs(v)})'
    if h == 'expect-no-attr': return f'ExpNoAttr({loc(x[1])}, {rs(x[2][1])})'
    if h in ('mark-metrics', 'expect-metric-delta', 'expect-metric-delta-at-most', 'expect-metric-delta-at-least'):
        return 'Mark'
    raise SystemExit(f'unknown step {h}')

def main():
    d, mod, out = sys.argv[1:4]
    skip = set(sys.argv[5:]) if len(sys.argv) > 4 and sys.argv[4] == '--skip' else set()
    tests = []
    for f in sorted(os.listdir(d)):
        if not f.endswith('.scm') or f[:-4] in skip: continue
        tree = parse(tokenize(open(os.path.join(d, f)).read()))
        for t in tree:
            assert t[0] == ('sym', 'test'), t[0]
            name = t[1][1]
            steps = [s for blk in t[2:] if blk[0] == ('sym', 'steps') for s in blk[1:]]
            tests.append((f[:-4], [step(s) for s in steps]))
    lines = ['import Spec', '', f'## Generated by tools/scm2roc.py from {d}', f'{mod} := [].{{', '\tall : List((Str, List(Spec.Step)))', '\tall = [']
    for name, steps in tests:
        lines.append(f'\t\t({rs(name)}, [')
        for s in steps: lines.append(f'\t\t\t{s},')
        lines.append('\t\t]),')
    lines += ['\t]', '}', '']
    open(out, 'w').write('\n'.join(lines))
    print(f'{len(tests)} specs, {sum(len(s) for _, s in tests)} steps -> {out}')

main()
