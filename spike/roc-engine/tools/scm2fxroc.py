"""scm2fxroc.py SPEC_DIR MODULE OUT.roc -- convert `.scm` specs with effects
(Conduit) into Roc data for src/FxSpec.roc. UI steps become `Ui(Spec.Step)`;
setup's initial-location and local-storage become the FxSpec.Setup; metric
steps become `Ui(Mark)` (the engine has no matching counters)."""
import sys, os
sys.argv, argv = sys.argv[:1], sys.argv
here = os.path.dirname(os.path.abspath(__file__))
src = open(os.path.join(here, 'scm2roc.py')).read().replace('\nmain()\n', '\n')
ns = {}
exec(compile(src, 'scm2roc.py', 'exec'), ns)
tokenize, parse, rs, step = ns['tokenize'], ns['parse'], ns['rs'], ns['step']
sys.argv = argv

def kw(x, name):
    for i in range(len(x) - 1):
        if x[i] == ('sym', name): return x[i + 1][1]
    raise SystemExit(f'missing {name} in {x}')

def fxstep(x):
    h = x[0][1]
    if h == 'expect-current-location': return f'ExpLocation({rs(x[1][1])})'
    if h == 'expect-document-title': return f'ExpTitle({rs(x[1][1])})'
    if h == 'expect-local-storage': return f'ExpStorage({rs(x[1][1])}, {rs(x[2][1])})'
    if h == 'expect-no-local-storage': return f'ExpNoStorage({rs(x[1][1])})'
    if h == 'expect-pending-effects': return f'ExpPending({x[1][1]})'
    if h == 'run-effect': return f'Run({x[1][1]})'
    if h == 'stub-http': return f'Stub({rs(kw(x, ":url"))}, {kw(x, ":status")}, {rs(kw(x, ":body"))})'
    if h == 'stub-http-reject': return f'Reject({rs(kw(x, ":kind"))}, {rs(kw(x, ":detail"))})'
    if h == 'history-back': return 'Back'
    if h == 'history-forward': return 'Forward'
    if h == 'navigate': return f'Navigate({rs(x[1][1])})'
    return f'Ui({step(x)})'

def main():
    d, mod, out = argv[1:4]
    tests = []
    for f in sorted(os.listdir(d)):
        if not f.endswith('.scm'): continue
        for t in parse(tokenize(open(os.path.join(d, f)).read())):
            url, storage, steps = '', [], []
            for blk in t[2:]:
                if blk[0] == ('sym', 'setup'):
                    for s in blk[1:]:
                        if s[0][1] == 'initial-location': url = s[1][1]
                        elif s[0][1] == 'local-storage': storage.append((s[1][1], s[2][1]))
                elif blk[0] == ('sym', 'steps'):
                    steps += [fxstep(s) for s in blk[1:]]
            tests.append((f[:-4], url, storage, steps))
    lines = ['import Spec', 'import FxSpec', '', f'## Generated by tools/scm2fxroc.py from {os.path.basename(os.path.dirname(os.path.abspath(d)))}/specs', f'{mod} := [].{{', '\tall : List((Str, FxSpec.Setup, List(FxSpec.Step)))', '\tall = [']
    for name, url, storage, steps in tests:
        st = ', '.join(f'({rs(k)}, {rs(v)})' for k, v in storage)
        lines.append(f'\t\t({rs(name)}, {{ url: {rs(url)}, storage: [{st}] }}, [')
        for s in steps: lines.append(f'\t\t\t{s},')
        lines.append('\t\t]),')
    lines += ['\t]', '}', '']
    open(out, 'w').write('\n'.join(lines))
    print(f'{len(tests)} specs, {sum(len(t[3]) for t in tests)} steps -> {out}')

main()
